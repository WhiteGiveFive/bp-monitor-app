#!/usr/bin/env python3
"""Export the ten frozen upstream LightGBM regressors and parity fixtures.

Schema v1: targets [SBP, DBP] each contain five seed models. A model contains
ordered trees. Tree parallel arrays are f (feature indices), t (thresholds),
l/r (child indices; a negative child is -leaf_index-1), m (missing mode:
0=None, 2=NaN), d (default-left flags), and v (leaf values). All numeric
values retain Python/JSON double precision. Sum trees directly: the initial
score and shrinkage are already present in leaf values. Average the five
models per target. The native predictor maps inputs whose absolute value is
at most inputZeroThreshold (the Float32 constant 1e-35) to zero before tree
evaluation. No extra intercept or neural output transform applies.

Dependencies: numpy, lightgbm. Synthetic fixtures are generated by default;
--prepared-dir also verifies the selected prepared recordings.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import lightgbm as lgb
import numpy as np

TARGETS = ("sbp", "dbp")
SEEDS = tuple(range(5))
FEATURE_COUNT = 161
INPUT_ZERO_THRESHOLD = float(np.float32(1e-35))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def compact_tree(info: dict) -> dict:
    if info.get("num_cat", 0):
        raise ValueError("Categorical trees are unsupported by schema v1")
    count = int(info["num_leaves"])
    tree = {key: [None] * (count - 1) for key in ("f", "t", "l", "r", "m", "d")}
    tree["v"] = [None] * count

    def visit(node: dict) -> int:
        if "leaf_index" in node or "split_index" not in node:
            if node.get("leaf_coeff") or node.get("leaf_features"):
                raise ValueError("Linear leaves are unsupported by schema v1")
            i = int(node.get("leaf_index", 0))
            if not 0 <= i < count or tree["v"][i] is not None:
                raise ValueError("Invalid or duplicate leaf index")
            tree["v"][i] = float(node["leaf_value"])
            return -i - 1
        i = int(node["split_index"])
        if not 0 <= i < count - 1 or tree["f"][i] is not None:
            raise ValueError("Invalid or duplicate split index")
        if node["decision_type"] != "<=":
            raise ValueError(f"Unsupported decision: {node['decision_type']}")
        missing_type = node["missing_type"]
        if missing_type not in ("None", "NaN"):
            raise ValueError(f"Unsupported missing type: {missing_type}")
        tree["f"][i] = int(node["split_feature"])
        tree["t"][i] = float(node["threshold"])
        tree["m"][i] = 2 if missing_type == "NaN" else 0
        tree["d"][i] = bool(node["default_left"])
        tree["l"][i] = visit(node["left_child"])
        tree["r"][i] = visit(node["right_child"])
        return i

    root = visit(info["tree_structure"])
    if root != (0 if count > 1 else -1):
        raise ValueError("Unexpected root index")
    if any(value is None for array in tree.values() for value in array):
        raise ValueError("Incomplete tree")
    if any(not 0 <= f < FEATURE_COUNT for f in tree["f"]):
        raise ValueError("Feature index outside the 161-feature schema")
    return tree


def fixture_inputs(dumps: list[dict], seed: int) -> tuple[list[str], np.ndarray]:
    """Seeded random cases plus null, zero and exact split-boundary cases."""
    rng = np.random.default_rng(seed)
    names = dumps[0]["feature_names"]
    ranges = dumps[0]["feature_infos"]
    low = np.array([ranges[name]["min_value"] for name in names], dtype=np.float64)
    high = np.array([ranges[name]["max_value"] for name in names], dtype=np.float64)
    mid = (low + high) / 2
    labels: list[str] = []
    rows: list[np.ndarray] = []

    def add(label: str, values: np.ndarray) -> None:
        labels.append(label)
        rows.append(values.copy())

    for label, value in (("all_zero", 0.0), ("all_negative_zero", -0.0),
                         ("all_missing", np.nan), ("all_tiny_positive", 1e-36),
                         ("all_tiny_negative", -1e-36), ("all_1e_minus35", 1e-35),
                         ("all_native_zero_positive", INPUT_ZERO_THRESHOLD),
                         ("all_native_zero_negative", -INPUT_ZERO_THRESHOLD),
                         ("all_above_native_zero", np.nextafter(INPUT_ZERO_THRESHOLD, np.inf)),
                         ("all_below_negative_native_zero", np.nextafter(-INPUT_ZERO_THRESHOLD, -np.inf))):
        add(label, np.full(FEATURE_COUNT, value, dtype=np.float64))
    add("all_minimum", low)
    add("all_maximum", high)
    add("all_midpoint", mid)
    for i in range(256):
        values = rng.uniform(low, high)
        if i % 2:
            values[rng.random(FEATURE_COUNT) < 0.3] = np.nan
        if i % 3 == 0:
            values[rng.random(FEATURE_COUNT) < 0.2] = 0.0
        add(f"random_{i:03}", values)
    for feature in range(FEATURE_COUNT):
        values = mid.copy()
        values[feature] = np.nan
        add(f"missing_feature_{feature:03}", values)

    # Include the exact Double threshold and both adjacent representable values.
    pairs: set[tuple[int, float]] = set()
    for dump in dumps:
        def gather(node: dict) -> None:
            if "split_index" in node:
                pairs.add((int(node["split_feature"]), float(node["threshold"])))
                gather(node["left_child"])
                gather(node["right_child"])
        for tree in dump["tree_info"]:
            gather(tree["tree_structure"])
    ordered = sorted(pairs)
    selection = set(rng.choice(len(ordered), size=min(128, len(ordered)), replace=False).tolist())
    selection.update(i for i, (_, threshold) in enumerate(ordered) if abs(threshold) < 1e-30)
    for index in sorted(selection):
        feature, threshold = ordered[index]
        for label, value in (("below", np.nextafter(threshold, -np.inf)),
                             ("at", threshold),
                             ("above", np.nextafter(threshold, np.inf))):
            values = mid.copy()
            values[feature] = value
            add(f"threshold_{feature}_{index}_{label}", values)
    return labels, np.stack(rows)


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, separators=(",", ":"), allow_nan=False) + "\n")


def export(model_dir: Path, output: Path, fixtures_output: Path, fixture_seed: int,
           prepared_dir: Path | None = None) -> dict:
    manifest_path = model_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    if not manifest.get("complete") or manifest["seeds"]["gbm"] != list(SEEDS):
        raise ValueError("Expected a complete upstream five-seed model bundle")
    feature_names = manifest["columns"]["gbm"]
    if len(feature_names) != FEATURE_COUNT or len(set(feature_names)) != FEATURE_COUNT:
        raise ValueError("Expected exactly 161 uniquely named ordered features")
    boosters: list[list[lgb.Booster]] = []
    targets: list[dict] = []
    dumps: list[dict] = []
    checksums = {}
    for target in TARGETS:
        target_models, target_boosters = [], []
        for seed in SEEDS:
            filename = f"gbm_seed{seed}_{target}.txt"
            path = model_dir / filename
            digest = sha256(path)
            if manifest["files"].get(filename) != digest:
                raise ValueError(f"Source checksum mismatch: {filename}")
            checksums[filename] = digest
            booster = lgb.Booster(model_file=str(path))
            dump = booster.dump_model()
            if dump["feature_names"] != feature_names:
                raise ValueError(f"Feature order mismatch: {filename}")
            if dump.get("num_class") != 1 or dump.get("num_tree_per_iteration") != 1:
                raise ValueError("Only scalar regression boosters are supported")
            if dump.get("average_output") or not dump["objective"].startswith("huber"):
                raise ValueError("Expected plain additive Huber regression output")
            if len(dump["tree_info"]) != 500:
                raise ValueError(f"Expected 500 trees: {filename}")
            target_models.append({"seed": seed, "trees": [compact_tree(t) for t in dump["tree_info"]]})
            target_boosters.append(booster)
            dumps.append(dump)
        targets.append({"name": target, "models": target_models})
        boosters.append(target_boosters)
    forest = {"schemaVersion": 1, "featureCount": FEATURE_COUNT,
              "inputZeroThreshold": INPUT_ZERO_THRESHOLD,
              "featureNames": feature_names, "targetOrder": list(TARGETS), "targets": targets,
              "sourceModelManifestSHA256": sha256(manifest_path), "sourceSHA256": checksums}
    write_json(output, forest)

    labels, values = fixture_inputs(dumps, fixture_seed)
    prepared_records = []
    if prepared_dir is not None:
        prepared_manifest = json.loads((prepared_dir / "manifest.json").read_text())
        for filename in prepared_manifest["recordings"]:
            if Path(filename).name != filename:
                raise ValueError("Prepared manifest must contain plain filenames")
            path = prepared_dir / filename
            if sha256(path) != prepared_manifest["preparation"]["files"][filename]:
                raise ValueError(f"Prepared recording checksum mismatch: {filename}")
            record = json.loads(path.read_text())
            features = np.asarray([np.nan if x is None else x for x in record["gbmFeatures"]], np.float64)
            if features.shape != (FEATURE_COUNT,) or np.isinf(features).any():
                raise ValueError(f"Invalid prepared features: {filename}")
            labels.append("prepared_" + record["id"])
            values = np.concatenate([values, features[None]], axis=0)
            prepared_records.append(record)
    # Shape: records, target, seed. Native Booster.predict includes no extra
    # output transform for the fixed Huber regression objective.
    per_seed = np.stack([np.stack([b.predict(values, num_threads=1) for b in group], axis=1)
                         for group in boosters], axis=1)
    average = per_seed.mean(axis=2)
    if not np.isfinite(per_seed).all():
        raise ValueError("Original boosters produced nonfinite parity predictions")
    reference_error = 0.0
    if prepared_records:
        expected = np.asarray([r["reference"]["lightGBM"] for r in prepared_records], np.float64)
        reference_error = float(np.max(np.abs(average[-len(prepared_records):] - expected)))
        if reference_error > 1e-10:
            raise ValueError(f"Prepared predictions disagree with historical references: {reference_error}")
    cases = [{"name": label,
              "features": [float(v) if np.isfinite(v) else None for v in row],
              "perSeed": seeded.tolist(), "prediction": prediction.tolist()}
             for label, row, seeded, prediction in zip(labels, values, per_seed, average)]
    fixtures = {"schemaVersion": 1, "randomSeed": fixture_seed, "modelSHA256": sha256(output),
                "lightgbmVersion": lgb.__version__, "absoluteTolerance": 1e-10,
                "preparedRecordCount": len(prepared_records),
                "preparedReferenceMaxAbsoluteError": reference_error, "cases": cases}
    write_json(fixtures_output, fixtures)
    return {"model": str(output), "modelBytes": output.stat().st_size,
            "fixtures": str(fixtures_output), "fixtureCount": len(cases),
            "preparedRecordCount": len(prepared_records), "preparedReferenceMaxAbsoluteError": reference_error,
            "models": 10, "trees": 5000, "sourceChecksumValidation": "passed"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("artifacts/models/trees.json"))
    parser.add_argument("--fixtures-output", type=Path, default=Path("artifacts/validation/tree_parity_fixtures.json"))
    parser.add_argument("--fixture-seed", type=int, default=20261022)
    parser.add_argument("--prepared-dir", type=Path)
    args = parser.parse_args()
    print(json.dumps(export(args.model_dir, args.output, args.fixtures_output, args.fixture_seed,
                            args.prepared_dir), indent=2))


if __name__ == "__main__":
    main()
